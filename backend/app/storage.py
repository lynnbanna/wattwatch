"""Image storage on local disk, outside the web root; files are only served via the API."""

import os
import re
import tempfile
from io import BytesIO
from pathlib import Path

from PIL import Image

from app.core.config import get_settings

_KEY = re.compile(r"^[0-9a-f]{64}\.png$")


def upload_dir() -> Path:
    path = Path(get_settings().upload_dir)
    path.mkdir(parents=True, exist_ok=True)
    return path


def image_path(key: str) -> Path:
    if not _KEY.fullmatch(key):  # keys are generated by us; refuse anything else
        raise ValueError(f"invalid image key {key!r}")
    return upload_dir() / key


def save_image(image: Image.Image, upload_sha256: str) -> str:
    """Store the decoded image as PNG without metadata (no EXIF or GPS); return its key.

    Keyed by the upload's SHA-256, so re-uploading the same file reuses one copy.
    """
    key = f"{upload_sha256}.png"
    target = image_path(key)
    if target.exists():
        return key
    buf = BytesIO()
    image.save(buf, format="PNG")
    fd, tmp = tempfile.mkstemp(dir=target.parent, suffix=".tmp")
    with os.fdopen(fd, "wb") as f:
        f.write(buf.getvalue())
    os.replace(tmp, target)
    return key


def delete_image(key: str) -> None:
    image_path(key).unlink(missing_ok=True)
